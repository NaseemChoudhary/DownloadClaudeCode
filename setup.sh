#!/usr/bin/env bash
set -euo pipefail

# Claude Code + OpenRouter interactive installer
# macOS / Linux / WSL / Git Bash
#
# NOTE:
# - Claude Code is installed using Anthropic's official installer.
# - OpenRouter is used as the Anthropic-compatible gateway.
# - A personal OpenRouter API key is required.
# - "Free" means OpenRouter free models/routes when supported; Claude/Anthropic
#   models themselves are not assumed to be free.

APP_DIR="${HOME}/.claude-openrouter"
CONFIG_FILE="${APP_DIR}/config.env"

bold() { printf '\033[1m%s\033[0m\n' "$1"; }
green() { printf '\033[32m✓\033[0m %s\n' "$1"; }
yellow() { printf '\033[33m!\033[0m %s\n' "$1"; }
red() { printf '\033[31m✗\033[0m %s\n' "$1" >&2; }
pause() { read -r -p "Press Enter to continue..." _; }

install_claude() {
  if command -v claude >/dev/null 2>&1; then
    green "Claude Code is already installed: $(claude --version 2>/dev/null || true)"
    return
  fi

  bold "Installing Claude Code..."
  curl -fsSL https://claude.ai/install.sh | bash

  export PATH="$HOME/.local/bin:$PATH"

  if ! command -v claude >/dev/null 2>&1; then
    yellow "Claude was installed, but this shell does not yet see ~/.local/bin."
    yellow "Restart your terminal, or run: export PATH=\"\$HOME/.local/bin:\$PATH\""
  else
    green "Claude Code installed: $(claude --version 2>/dev/null || true)"
  fi
}

configure_openrouter() {
  mkdir -p "$APP_DIR"
  chmod 700 "$APP_DIR"

  echo
  bold "OpenRouter configuration"
  echo "Create/get your key at: https://openrouter.ai/keys"
  echo
  read -r -s -p "OpenRouter API key (sk-or-...): " OPENROUTER_API_KEY
  echo

  if [[ -z "$OPENROUTER_API_KEY" ]]; then
    red "No API key entered."
    return 1
  fi

  if [[ "$OPENROUTER_API_KEY" != sk-or-* ]]; then
    yellow "Warning: the key does not start with sk-or-. Continuing anyway."
  fi

  # Default to the official OpenRouter Free Models Router.
  # Important: Claude Code's native integration is designed for Anthropic
  # models. The free router may select non-Anthropic models, so this is
  # offered as an experimental free mode, not a guaranteed Claude mode.
  echo
  echo "Choose a mode:"
  echo "  1) Claude/Anthropic via OpenRouter (may cost money)"
  echo "  2) OpenRouter free router (experimental with Claude Code)"
  read -r -p "Choice [1-2, default 2]: " MODE
  MODE="${MODE:-2}"

  case "$MODE" in
    1)
      MODEL="~anthropic/claude-sonnet-latest"
      ;;
    2)
      MODEL="openrouter/free"
      ;;
    *)
      red "Invalid choice."
      return 1
      ;;
  esac

  cat > "$CONFIG_FILE" <<EOF
# Claude Code + OpenRouter
# Generated by setup.sh
export OPENROUTER_API_KEY=$(printf '%q' "$OPENROUTER_API_KEY")
export ANTHROPIC_BASE_URL="https://openrouter.ai/api"
export ANTHROPIC_AUTH_TOKEN="\$OPENROUTER_API_KEY"
export ANTHROPIC_API_KEY=""

# Selected model:
export ANTHROPIC_DEFAULT_SONNET_MODEL=$(printf '%q' "$MODEL")
export ANTHROPIC_DEFAULT_OPUS_MODEL=$(printf '%q' "$MODEL")
export ANTHROPIC_DEFAULT_HAIKU_MODEL=$(printf '%q' "$MODEL")
EOF

  chmod 600 "$CONFIG_FILE"

  # Load it for the current shell.
  # shellcheck disable=SC1090
  source "$CONFIG_FILE"

  green "OpenRouter configuration saved to $CONFIG_FILE"
  yellow "The API key is stored with permissions 600."
}

configure_shell_profile() {
  local profile=""
  case "${SHELL:-}" in
    */zsh) profile="$HOME/.zshrc" ;;
    */bash) profile="$HOME/.bashrc" ;;
  esac

  if [[ -z "$profile" ]]; then
    yellow "Could not identify bash/zsh profile automatically."
    echo "Run this before using Claude Code:"
    echo "  source \"$CONFIG_FILE\""
    return
  fi

  local marker="# >>> claude-code-openrouter >>>"
  if grep -Fq "$marker" "$profile" 2>/dev/null; then
    green "Shell profile already configured: $profile"
    return
  fi

  {
    echo
    echo "$marker"
    echo "[ -f \"$CONFIG_FILE\" ] && source \"$CONFIG_FILE\""
    echo "# <<< claude-code-openrouter <<<"
  } >> "$profile"

  green "Added OpenRouter configuration to $profile"
  echo "Open a new terminal or run:"
  echo "  source \"$profile\""
}

verify() {
  echo
  bold "Verification"

  if ! command -v claude >/dev/null 2>&1; then
    export PATH="$HOME/.local/bin:$PATH"
  fi

  if command -v claude >/dev/null 2>&1; then
    green "Claude Code: $(claude --version 2>/dev/null || echo installed)"
  else
    red "Claude command is not available yet."
    return 1
  fi

  [[ -n "${OPENROUTER_API_KEY:-}" ]] && green "OpenRouter key: loaded"
  [[ "${ANTHROPIC_BASE_URL:-}" == "https://openrouter.ai/api" ]] && green "OpenRouter endpoint: configured"
  [[ -z "${ANTHROPIC_API_KEY:-}" ]] && green "Anthropic API key: explicitly empty"
  echo
  echo "If Claude Code has an existing Anthropic login, run:"
  echo "  claude"
  echo "and then:"
  echo "  /logout"
  echo
  echo "Then restart Claude Code so the OpenRouter environment is used."
}

main_menu() {
  while true; do
    echo
    bold "Claude Code + OpenRouter"
    echo "================================"
    echo "  1) Install Claude Code"
    echo "  2) Configure OpenRouter"
    echo "  3) Configure shell profile"
    echo "  4) Verify setup"
    echo "  5) Install + configure everything"
    echo "  6) Show current configuration"
    echo "  7) Exit"
    echo
    read -r -p "Select [1-7]: " choice

    case "$choice" in
      1) install_claude ;;
      2) configure_openrouter ;;
      3) configure_shell_profile ;;
      4) verify ;;
      5)
        install_claude
        configure_openrouter
        configure_shell_profile
        verify
        ;;
      6)
        if [[ -f "$CONFIG_FILE" ]]; then
          echo "Config: $CONFIG_FILE"
          echo "Model: $(grep 'ANTHROPIC_DEFAULT_SONNET_MODEL=' "$CONFIG_FILE" | sed 's/.*=//')"
          echo "Key: configured"
        else
          yellow "No configuration found."
        fi
        ;;
      7) exit 0 ;;
      *) red "Invalid option." ;;
    esac
  done
}

# Windows users should use setup.ps1, not this file.
if [[ "${OSTYPE:-}" == msys* || "${OSTYPE:-}" == cygwin* ]]; then
  yellow "You appear to be running Git Bash on Windows."
  yellow "For the native Windows installer, use setup.ps1 instead."
fi

main_menu
